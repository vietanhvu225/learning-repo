"""Build deterministic Markdown views from the repository registry."""

from __future__ import annotations

import posixpath
from collections import defaultdict
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from .metadata import MetadataError, load_yaml_mapping


GENERATED_MARKER = "<!-- Generated by repo-learning. Do not edit manually. -->"
MANAGED_DIRECTORIES = (
    Path("indexes/by-tag"),
    Path("indexes/by-status"),
    Path("indexes/by-adoption"),
)


def build_index_documents(root: Path) -> dict[Path, str]:
    """Render every managed index into an in-memory path/content mapping."""

    registry_path = root / "registry" / "repositories.yaml"
    registry = load_yaml_mapping(registry_path)
    entries = registry.get("repositories", [])
    if not isinstance(entries, list) or not all(isinstance(entry, dict) for entry in entries):
        raise MetadataError(f"repositories must be a list of mappings in {registry_path}")
    ordered = sorted(entries, key=lambda entry: str(entry.get("canonical_id", "")))

    documents: dict[Path, str] = {}
    all_path = Path("indexes/all-repositories.md")
    documents[all_path] = _render_repository_table("All repositories", ordered, all_path)

    view_specs = (
        ("tag", "tags", Path("indexes/by-tag"), "Repositories by tag"),
        ("status", "status", Path("indexes/by-status"), "Repositories by status"),
        (
            "adoption decision",
            "adoption",
            Path("indexes/by-adoption"),
            "Repositories by adoption decision",
        ),
    )
    for singular, field, directory, landing_title in view_specs:
        grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for entry in ordered:
            raw_values = entry.get(field, [])
            values = raw_values if isinstance(raw_values, list) else [raw_values]
            for value in values:
                if value is not None and str(value).strip():
                    grouped[str(value)].append(entry)

        landing_path = directory / "README.md"
        documents[landing_path] = _render_landing(
            landing_title, singular, grouped
        )
        for value in sorted(grouped):
            page_path = directory / f"{value}.md"
            documents[page_path] = _render_repository_table(
                f"{landing_title}: `{value}`", grouped[value], page_path
            )

    return documents


def write_index_documents(root: Path, documents: Mapping[Path, str]) -> None:
    """Write changed generated files and remove obsolete generated child pages."""

    normalized_documents = {Path(path): content for path, content in documents.items()}
    intended = {path.as_posix() for path in normalized_documents}
    for directory in MANAGED_DIRECTORIES:
        absolute_directory = root / directory
        if not absolute_directory.exists():
            continue
        for candidate in absolute_directory.glob("*.md"):
            relative = candidate.relative_to(root)
            if relative.as_posix() in intended:
                continue
            try:
                content = candidate.read_text(encoding="utf-8-sig")
            except (OSError, UnicodeError):
                continue
            if GENERATED_MARKER in content:
                candidate.unlink()

    for relative_path, content in sorted(
        normalized_documents.items(), key=lambda item: item[0].as_posix()
    ):
        destination = root / relative_path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            current = destination.read_text(encoding="utf-8-sig")
            if current == content:
                continue
        destination.write_text(content, encoding="utf-8", newline="\n")


def _render_landing(
    title: str,
    singular: str,
    grouped: Mapping[str, list[dict[str, Any]]],
) -> str:
    lines = [f"# {title}", "", GENERATED_MARKER, ""]
    if not grouped:
        lines.append(f"No {singular} views are available.")
    else:
        for value in sorted(grouped):
            lines.append(f"- [`{value}`]({value}.md) ({len(grouped[value])})")
    return "\n".join(lines) + "\n"


def _render_repository_table(
    title: str,
    entries: list[dict[str, Any]],
    output_path: Path,
) -> str:
    lines = [f"# {title}", "", GENERATED_MARKER, ""]
    if not entries:
        lines.append("No repositories are registered.")
        return "\n".join(lines) + "\n"

    lines.extend(
        [
            "| Repository | Status | Adoption | Tags |",
            "|---|---|---|---|",
        ]
    )
    for entry in entries:
        canonical_id = _cell(entry.get("canonical_id", "unknown"))
        analysis_path = str(entry.get("analysis_path", ""))
        link = posixpath.relpath(analysis_path, start=output_path.parent.as_posix())
        status = _cell(entry.get("status", ""))
        adoption = _cell(entry.get("adoption", ""))
        raw_tags = entry.get("tags", [])
        tags = ", ".join(map(str, raw_tags)) if isinstance(raw_tags, list) else str(raw_tags)
        lines.append(
            f"| [{canonical_id}]({link}) | {status} | {adoption} | {_cell(tags)} |"
        )
    return "\n".join(lines) + "\n"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")

