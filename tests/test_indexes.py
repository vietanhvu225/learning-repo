from __future__ import annotations

import os
from pathlib import Path

import yaml

from repo_learning.indexes import build_index_documents, write_index_documents


GENERATED_MARKER = "<!-- Generated by repo-learning. Do not edit manually. -->"


def _entry(
    canonical_id: str,
    analysis_path: str,
    *,
    tags: list[str],
    status: str,
    adoption: str,
) -> dict[str, object]:
    return {
        "canonical_id": canonical_id,
        "repo": "/".join(canonical_id.split("/")[1:]),
        "url": f"https://{canonical_id}",
        "analysis_path": analysis_path,
        "analyzed_commit": "a" * 40,
        "status": status,
        "adoption": adoption,
        "confidence": "high",
        "tags": tags,
    }


def _write_registry(root: Path) -> None:
    registry = root / "registry"
    registry.mkdir(parents=True)
    entries = [
        _entry(
            "github.com/zeta/tool",
            "analyses/github/zeta--tool/README.md",
            tags=["workflow-automation", "ai-agents"],
            status="needs-review",
            adoption="experiment",
        ),
        _entry(
            "github.com/alpha/tool",
            "analyses/github/alpha--tool/README.md",
            tags=["ai-agents"],
            status="analyzed",
            adoption="adopt-now",
        ),
    ]
    (registry / "repositories.yaml").write_text(
        yaml.safe_dump(
            {"schema_version": 1, "repositories": entries}, sort_keys=False
        ),
        encoding="utf-8",
    )


def test_build_index_documents_is_deterministic_and_uses_relative_links(
    tmp_path: Path,
) -> None:
    _write_registry(tmp_path)

    first = build_index_documents(tmp_path)
    second = build_index_documents(tmp_path)

    assert first == second
    assert Path("indexes/all-repositories.md") in first
    assert Path("indexes/by-tag/ai-agents.md") in first
    assert Path("indexes/by-tag/workflow-automation.md") in first
    assert Path("indexes/by-status/analyzed.md") in first
    assert Path("indexes/by-status/needs-review.md") in first
    assert Path("indexes/by-adoption/adopt-now.md") in first
    assert Path("indexes/by-adoption/experiment.md") in first
    all_repositories = first[Path("indexes/all-repositories.md")]
    assert all_repositories.index("github.com/alpha/tool") < all_repositories.index(
        "github.com/zeta/tool"
    )
    assert "../analyses/github/alpha--tool/README.md" in all_repositories
    assert (
        "../../analyses/github/alpha--tool/README.md"
        in first[Path("indexes/by-tag/ai-agents.md")]
    )
    assert all(GENERATED_MARKER in content for content in first.values())


def test_write_indexes_removes_stale_generated_pages_without_touching_reports(
    tmp_path: Path,
) -> None:
    _write_registry(tmp_path)
    report = tmp_path / "analyses/github/alpha--tool/README.md"
    report.parent.mkdir(parents=True)
    report.write_bytes(b"analysis remains unchanged\n")
    original_report = report.read_bytes()
    stale = tmp_path / "indexes/by-tag/stale.md"
    stale.parent.mkdir(parents=True)
    stale.write_text(f"{GENERATED_MARKER}\n\nold\n", encoding="utf-8")

    write_index_documents(tmp_path, build_index_documents(tmp_path))

    assert not stale.exists()
    assert report.read_bytes() == original_report


def test_write_indexes_does_not_rewrite_unchanged_content(tmp_path: Path) -> None:
    _write_registry(tmp_path)
    documents = build_index_documents(tmp_path)
    write_index_documents(tmp_path, documents)
    target = tmp_path / "indexes/all-repositories.md"
    historical_time = 1_000_000_000
    os.utime(target, (historical_time, historical_time))

    write_index_documents(tmp_path, build_index_documents(tmp_path))

    assert target.stat().st_mtime == historical_time
